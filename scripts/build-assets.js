// Copies the Tabler icons and Montserrat font the UI uses into src/, so the packaged app needs no node_modules.
// Run: node scripts/build-assets.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const ICONS = ['device-gamepad-2', 'brand-steam', 'brand-itch', 'device-desktop', 'search', 'x', 'refresh', 'plus', 'settings', 'sun', 'moon',
  'player-play', 'folder', 'folder-open', 'folder-plus', 'clock', 'calendar', 'layout-grid', 'list', 'star', 'eye', 'eye-off', 'pencil', 'photo',
  'chart-bar', 'loader-2', 'check', 'alert-triangle', 'info-circle', 'external-link', 'file', 'trash', 'dots-vertical', 'hourglass', 'trophy',
  'cloud-download', 'key', 'user-circle', 'ghost', 'arrow-up', 'arrow-down', 'circle-check', 'circle-x', 'download', 'world', 'flame',
  'clock-play', 'database', 'apps', 'sort-descending', 'terminal-2', 'brand-github', 'puzzle', 'brand-discord', 'arrow-back-up', 'drag-drop'];
const FILLED = ['star', 'player-play'];
const dir = path.join(root, 'node_modules/@tabler/icons/icons');
const strip = (svg) => svg.replace(/<svg[\s\S]*?>/, '').replace(/<\/svg>/, '').replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none" \/>/, '').replace(/\s+/g, ' ').trim();
const out = {};
for (const n of ICONS) out[n] = strip(fs.readFileSync(path.join(dir, 'outline', n + '.svg'), 'utf8'));
for (const n of FILLED) out[n + '-filled'] = strip(fs.readFileSync(path.join(dir, 'filled', n + '.svg'), 'utf8'));
fs.writeFileSync(path.join(root, 'src/icons.js'),
  '// Generated by scripts/build-assets.js from Tabler Icons (MIT, tabler.io/icons). Do not edit by hand.\nwindow.TABLER = ' + JSON.stringify(out, null, 0) + ';\n');
fs.mkdirSync(path.join(root, 'src/fonts'), { recursive: true });
for (const w of [400, 500, 600, 700]) {
  fs.copyFileSync(path.join(root, `node_modules/@fontsource/montserrat/files/montserrat-latin-${w}-normal.woff2`), path.join(root, `src/fonts/montserrat-${w}.woff2`));
  fs.copyFileSync(path.join(root, `node_modules/@fontsource/montserrat/files/montserrat-latin-ext-${w}-normal.woff2`), path.join(root, `src/fonts/montserrat-ext-${w}.woff2`));
}
console.log('icons:', Object.keys(out).length, 'fonts: 8');
